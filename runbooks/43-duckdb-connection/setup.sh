#!/usr/bin/env bash
# Opens the two port-forwards the exercise needs and writes a ready-to-paste init.local.sql.
source "$(dirname "$0")/../lib.sh"
NS=lakehouse
HERE="$(cd "$(dirname "$0")" && pwd)"
PIDFILE="$HERE/.port-forward.pid"

kubectl -n $NS get svc iceberg-rest >/dev/null 2>&1 || {
  echo "lakehouse not deployed — see LAKEHOUSE.md"; exit 1; }

"$HERE/cleanup.sh" >/dev/null 2>&1 || true
: > "$PIDFILE"

for pair in "iceberg-rest 8181" "garage 3900"; do
  set -- $pair
  if ss -ltn 2>/dev/null | grep -q ":$2 "; then
    echo "port $2 already in use — assuming your own forward is up for $1"
    continue
  fi
  nohup kubectl -n $NS port-forward "svc/$1" "$2:$2" >"$HERE/.pf-$1.log" 2>&1 &
  echo $! >> "$PIDFILE"
done

for p in 8181 3900; do
  for _ in $(seq 1 20); do ss -ltn 2>/dev/null | grep -q ":$p " && break; sleep 1; done
done

KID=$(kubectl -n $NS get secret lakehouse-s3-credentials -o jsonpath='{.data.access-key-id}' | base64 -d)
SEC=$(kubectl -n $NS get secret lakehouse-s3-credentials -o jsonpath='{.data.secret-access-key}' | base64 -d)

cat > "$HERE/init.local.sql" <<SQL
-- Generated by setup.sh. Contains LIVE S3 credentials (read+write on the lakehouse bucket).
-- Gitignored. Delete it with cleanup.sh when you're done.
INSTALL iceberg; LOAD iceberg;
INSTALL httpfs;  LOAD httpfs;

CREATE OR REPLACE SECRET garage (
    TYPE s3,
    KEY_ID '$KID',
    SECRET '$SEC',
    REGION 'garage',
    ENDPOINT '127.0.0.1:3900',
    URL_STYLE 'path',
    USE_SSL false
);

ATTACH IF NOT EXISTS 'warehouse' AS lake (
    TYPE iceberg,
    ENDPOINT 'http://127.0.0.1:8181',
    AUTHORIZATION_TYPE 'none'
);
SQL
chmod 600 "$HERE/init.local.sql"

cat <<MSG

Forwards up: catalog on 127.0.0.1:8181, S3 on 127.0.0.1:3900.
They are reachable from Windows too — WSL2 relays listening sockets to the host.

Ready-to-paste connection SQL (live credentials, gitignored):
  $HERE/init.local.sql

Try it without peeking at the solution first. When you want the shortcut:
  duckdb -init $HERE/init.local.sql
MSG
